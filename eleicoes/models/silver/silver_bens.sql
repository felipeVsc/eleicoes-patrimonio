SELECT
    * EXCLUDE (
        VR_BEM_CANDIDATO,
        ANO_ELEICAO,
        CD_ELEICAO,
        SQ_CANDIDATO,
        NR_ORDEM_BEM_CANDIDATO,
        CD_TIPO_BEM_CANDIDATO
    ),
    CAST(
        REPLACE(VR_BEM_CANDIDATO, ',', '.') AS DECIMAL(18, 2)
    ) AS VR_BEM_CANDIDATO,
    CAST(ANO_ELEICAO AS INT) AS ANO_ELEICAO,
    CAST(CD_ELEICAO AS INT) AS CD_ELEICAO,
    CAST(SQ_CANDIDATO AS BIGINT) AS SQ_CANDIDATO,
    CAST(NR_ORDEM_BEM_CANDIDATO AS INT) AS NR_ORDEM_BEM_CANDIDATO,
    CAST(CD_TIPO_BEM_CANDIDATO AS INT) AS CD_TIPO_BEM_CANDIDATO
FROM {{ source('eleicoes', 'bens') }}
WHERE DS_TIPO_BEM_CANDIDATO NOT IN ('#NULO', '#NULO#', 'NULO')